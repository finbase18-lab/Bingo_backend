BINGO_TOTAL_NUMBERS = 75
BINGO_DEFAULT_COUNTDOWN_SECONDS = 60
BINGO_DEFAULT_MIN_PLAYERS = 2


def _bingo_parse_card(card_data):
    """Convert stored Bingo card JSON into a 5x5 integer grid."""
    import json

    if isinstance(card_data, str):
        grid = json.loads(card_data)
    else:
        grid = card_data

    if not isinstance(grid, list) or len(grid) != 5:
        raise ValueError("Invalid Bingo card grid")

    normalized = []
    for row in grid:
        if not isinstance(row, list) or len(row) != 5:
            raise ValueError("Invalid Bingo card row")
        normalized.append([int(value) for value in row])

    return normalized


def _bingo_marked(grid, called_numbers):
    """Return a 5x5 boolean grid. The center FREE square is always marked."""
    called = {int(number) for number in called_numbers}
    marked = []

    for r in range(5):
        row = []
        for c in range(5):
            value = grid[r][c]
            row.append(value == 0 or value in called)
        marked.append(row)

    return marked


def bingo_card_matches_pattern(card_data, called_numbers, pattern_key):
    """Check whether a card currently satisfies one enabled Bingo pattern."""
    grid = _bingo_parse_card(card_data)
    marked = _bingo_marked(grid, called_numbers)
    key = str(pattern_key).upper().strip()

    if key == "HORIZONTAL":
        return any(all(marked[r][c] for c in range(5)) for r in range(5))

    if key == "VERTICAL":
        return any(all(marked[r][c] for r in range(5)) for c in range(5))

    if key == "DIAGONAL":
        return (
            all(marked[i][i] for i in range(5))
            or all(marked[i][4 - i] for i in range(5))
        )

    if key == "FOUR_CORNERS":
        return (
            marked[0][0]
            and marked[0][4]
            and marked[4][0]
            and marked[4][4]
        )

    if key == "X":
        return (
            all(marked[i][i] for i in range(5))
            and all(marked[i][4 - i] for i in range(5))
        )

    if key == "PLUS":
        return (
            all(marked[2][c] for c in range(5))
            and all(marked[r][2] for r in range(5))
        )

    if key in ("FULL_HOUSE", "BLACKOUT"):
        return all(marked[r][c] for r in range(5) for c in range(5))

    return False


