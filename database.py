def join_bingo_round(round_id, telegram_user_id, card_id):
    """Join one cartel and pay the bet from BONUS -> DEPOSITED -> WITHDRAWABLE.

    A single bet may be split across more than one wallet bucket.  The whole
    operation is transactional, so a cartel is never reserved unless the
    complete bet can be paid.
    """
    connection = get_connection()
    try:
        connection.execute("BEGIN IMMEDIATE")

        user = connection.execute(
            "SELECT * FROM users WHERE telegram_user_id = ?", (telegram_user_id,)
        ).fetchone()
        if not user:
            connection.rollback()
            return None, "user_not_found"

        round_row = connection.execute(
            """SELECT r.*, rm.bet_amount, rm.max_players, rm.max_cards, rm.min_players
               FROM bingo_rounds r
               JOIN bingo_rooms rm ON rm.id = r.room_id
               WHERE r.id = ?""",
            (round_id,),
        ).fetchone()
        if not round_row:
            connection.rollback()
            return None, "round_not_found"
        if round_row["status"] not in ("WAITING", "COUNTDOWN"):
            connection.rollback()
            return None, "round_started"

        active_count = int(connection.execute(
            "SELECT COUNT(*) AS n FROM bingo_players WHERE round_id = ? AND status = 'ACTIVE'",
            (round_id,),
        ).fetchone()["n"] or 0)
        unique_player_count = int(connection.execute(
            "SELECT COUNT(DISTINCT user_id) AS n FROM bingo_players WHERE round_id = ? AND status = 'ACTIVE'",
            (round_id,),
        ).fetchone()["n"] or 0)
        already_in_round = connection.execute(
            "SELECT 1 FROM bingo_players WHERE round_id = ? AND user_id = ? AND status = 'ACTIVE' LIMIT 1",
            (round_id, user["id"]),
        ).fetchone() is not None
        if unique_player_count >= int(round_row["max_players"]) and not already_in_round:
            connection.rollback()
            return None, "room_full"

        selected_card_count = int(connection.execute(
            "SELECT COUNT(*) AS n FROM bingo_players WHERE round_id = ?",
            (round_id,),
        ).fetchone()["n"] or 0)
        if selected_card_count >= int(round_row["max_cards"]):
            connection.rollback()
            return None, "cards_full"

        card = connection.execute(
            "SELECT * FROM bingo_cards WHERE id = ? AND is_active = 1", (card_id,)
        ).fetchone()
        if not card:
            connection.rollback()
            return None, "card_not_found"

        occupied = connection.execute(
            """SELECT id FROM bingo_players
               WHERE round_id = ? AND card_id = ? AND status = 'ACTIVE'""",
            (round_id, card_id),
        ).fetchone()
        if occupied:
            connection.rollback()
            return None, "card_taken"

        duplicate = connection.execute(
            """SELECT id FROM bingo_players
               WHERE round_id = ? AND user_id = ? AND card_id = ?""",
            (round_id, user["id"], card_id),
        ).fetchone()
        if duplicate:
            connection.rollback()
            return None, "already_joined_card"

        bet = round(float(round_row["bet_amount"]), 2)
        bonus = round(float(user["bonus_balance"] or 0), 2)
        deposited = round(float(user["main_balance"] or 0), 2)
        withdrawable = round(float(user["withdrawable_balance"] or 0), 2)

        if round(bonus + deposited + withdrawable, 2) < bet:
            connection.rollback()
            return None, "insufficient_balance"

        remaining = bet
        deductions = []
        for column, label, available in (
            ("bonus_balance", "bonus_balance", bonus),
            ("main_balance", "main_balance", deposited),
            ("withdrawable_balance", "withdrawable_balance", withdrawable),
        ):
            if remaining <= 0:
                break
            used = round(min(available, remaining), 2)
            if used <= 0:
                continue
            before = available
            after = round(before - used, 2)
            connection.execute(
                f"UPDATE users SET {column} = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                (after, user["id"]),
            )
            deductions.append((label, used, before, after))
            remaining = round(remaining - used, 2)

        cur = connection.execute(
            """INSERT INTO bingo_players
               (round_id, user_id, card_id, bet_amount, status)
               VALUES (?, ?, ?, ?, 'ACTIVE')""",
            (round_id, user["id"], card_id, bet),
        )

        for balance_type, used, before, after in deductions:
            connection.execute(
                """INSERT INTO wallet_transactions
                   (user_id, transaction_type, balance_type, amount,
                    balance_before, balance_after, description)
                   VALUES (?, ?, ?, ?, ?, ?, ?)""",
                (user["id"], "BINGO_BET", balance_type, -used,
                 before, after, f"Bingo round #{round_row['round_number']} bet"),
            )

        # Countdown starts when the configured minimum number of selected
        # cartels/players has joined.  Additional cartels remain selectable
        # until the countdown reaches zero.
        new_unique_count = unique_player_count + (0 if already_in_round else 1)
        min_players = int(round_row["min_players"] or 2)
        if new_unique_count >= min_players and round_row["status"] == "WAITING":
            connection.execute(
                """UPDATE bingo_rounds
                   SET status = 'COUNTDOWN', countdown_started_at = CURRENT_TIMESTAMP,
                       started_at = CURRENT_TIMESTAMP
                   WHERE id = ? AND status = 'WAITING'""",
                (round_id,),
            )

        connection.commit()
        player = connection.execute(
            "SELECT * FROM bingo_players WHERE id = ?", (cur.lastrowid,)
        ).fetchone()
        return player, "joined"
    except DB_INTEGRITY_ERRORS:
        connection.rollback()
        return None, "card_taken"
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()

