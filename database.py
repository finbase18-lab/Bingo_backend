def init_database():

    connection = get_connection()

    try:

        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                telegram_user_id INTEGER NOT NULL UNIQUE,

                username TEXT,
                first_name TEXT,
                last_name TEXT,

                phone_number TEXT,

                referral_code TEXT NOT NULL UNIQUE,

                referred_by INTEGER,

                registration_bonus REAL NOT NULL DEFAULT 0,
                referral_bonus REAL NOT NULL DEFAULT 0,

                main_balance REAL NOT NULL DEFAULT 0,
                bonus_balance REAL NOT NULL DEFAULT 0,
                withdrawable_balance REAL NOT NULL DEFAULT 0,

                total_deposited REAL NOT NULL DEFAULT 0,
                total_withdrawn REAL NOT NULL DEFAULT 0,
                total_won REAL NOT NULL DEFAULT 0,

                is_blocked INTEGER NOT NULL DEFAULT 0,

                registered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (referred_by)
                    REFERENCES users(id)
            );


            CREATE TABLE IF NOT EXISTS referral_rewards (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                referrer_user_id INTEGER NOT NULL,
                referred_user_id INTEGER NOT NULL,

                amount REAL NOT NULL DEFAULT 0,

                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                UNIQUE (
                    referrer_user_id,
                    referred_user_id
                ),

                FOREIGN KEY (referrer_user_id)
                    REFERENCES users(id),

                FOREIGN KEY (referred_user_id)
                    REFERENCES users(id)
            );


            CREATE TABLE IF NOT EXISTS wallet_transactions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                user_id INTEGER NOT NULL,

                transaction_type TEXT NOT NULL,

                balance_type TEXT NOT NULL,

                amount REAL NOT NULL,

                balance_before REAL NOT NULL,

                balance_after REAL NOT NULL,

                description TEXT,

                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
            );


            CREATE TABLE IF NOT EXISTS demo_banks (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                bank_name TEXT NOT NULL,

                account_name TEXT NOT NULL,

                account_number TEXT NOT NULL UNIQUE,

                is_active INTEGER NOT NULL DEFAULT 1
            );


            CREATE TABLE IF NOT EXISTS deposit_requests (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                user_id INTEGER NOT NULL,

                bank_id INTEGER NOT NULL,

                amount REAL NOT NULL,

                transaction_id TEXT,

                status TEXT NOT NULL DEFAULT 'PENDING',

                admin_note TEXT,

                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                processed_at TEXT,

                FOREIGN KEY (user_id)
                    REFERENCES users(id),

                FOREIGN KEY (bank_id)
                    REFERENCES demo_banks(id)
            );


            CREATE TABLE IF NOT EXISTS system_settings (
                setting_key TEXT PRIMARY KEY,
                setting_value TEXT NOT NULL,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );


            CREATE TABLE IF NOT EXISTS withdrawal_requests (
                id INTEGER PRIMARY KEY AUTOINCREMENT,

                user_id INTEGER NOT NULL,

                bank_id INTEGER,

                amount REAL NOT NULL,

                account_number TEXT NOT NULL,

                account_name TEXT NOT NULL,

                status TEXT NOT NULL DEFAULT 'PENDING',

                admin_note TEXT,

                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,

                processed_at TEXT,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
            );
            """
        )

        # --------------------------------------------------------
        # PostgreSQL migration: Telegram IDs must be BIGINT.
        # The first version of the Render database used INTEGER (32-bit),
        # which causes "integer out of range" for larger Telegram IDs.
        # CREATE TABLE IF NOT EXISTS does not change an existing column, so
        # explicitly upgrade existing PostgreSQL tables here.
        # --------------------------------------------------------

        if USE_POSTGRES:
            for table_name in ("users", "admin_users"):
                column = connection.execute(
                    """
                    SELECT data_type
                    FROM information_schema.columns
                    WHERE table_schema = current_schema()
                      AND table_name = %s
                      AND column_name = 'telegram_user_id'
                    """,
                    (table_name,),
                ).fetchone()

                if column and str(column["data_type"]).lower() != "bigint":
                    connection.execute(
                        f'ALTER TABLE "{table_name}" ALTER COLUMN telegram_user_id TYPE BIGINT'
                    )

        # --------------------------------------------------------
        # Add demo banks if they do not already exist
        # --------------------------------------------------------

        banks = [
            (
                "Demo Commercial Bank",
                "Bingo Demo Account",
                "1000000001"
            ),
            (
                "Demo National Bank",
                "Bingo Demo Account",
                "2000000002"
            ),
            (
                "Demo United Bank",
                "Bingo Demo Account",
                "3000000003"
            ),
        ]

        for bank in banks:

            connection.execute(
                """
                INSERT OR IGNORE INTO demo_banks (
                    bank_name,
                    account_name,
                    account_number
                )
                VALUES (?, ?, ?)
                """,
                bank
            )

        # --------------------------------------------------------
        # Safe migration for existing bingo.db files
        # --------------------------------------------------------
        # Older databases may have been created before processed_at
        # was added. CREATE TABLE IF NOT EXISTS does not add missing
        # columns, so add them safely here without deleting data.
        for table in ("deposit_requests", "withdrawal_requests"):
            columns = {
                row["name"]
                for row in connection.execute(
                    f"PRAGMA table_info({table})"
                ).fetchall()
            }

            if "processed_at" not in columns:
                connection.execute(
                    f"ALTER TABLE {table} ADD COLUMN processed_at TEXT"
                )

        # Add bank_id to older withdrawal tables without deleting any data.
        withdrawal_columns = {
            row["name"]
            for row in connection.execute(
                "PRAGMA table_info(withdrawal_requests)"
            ).fetchall()
        }

        if "bank_id" not in withdrawal_columns:
            connection.execute(
                "ALTER TABLE withdrawal_requests ADD COLUMN bank_id INTEGER"
            )

        deposit_columns = {
            row["name"]
            for row in connection.execute(
                "PRAGMA table_info(deposit_requests)"
            ).fetchall()
        }

        if "transaction_id" not in deposit_columns:
            connection.execute(
                "ALTER TABLE deposit_requests ADD COLUMN transaction_id TEXT"
            )

        # Safe migration for Bingo rounds created by the previous database step.
        bingo_round_columns = {
            row["name"]
            for row in connection.execute(
                "PRAGMA table_info(bingo_rounds)"
            ).fetchall()
        }

        if bingo_round_columns and "commission_percent" not in bingo_round_columns:
            connection.execute(
                "ALTER TABLE bingo_rounds ADD COLUMN commission_percent REAL NOT NULL DEFAULT 10"
            )

        if bingo_round_columns and "bet_amount" not in bingo_round_columns:
            connection.execute(
                "ALTER TABLE bingo_rounds ADD COLUMN bet_amount REAL NOT NULL DEFAULT 0"
            )

        if bingo_round_columns and "winner_started_at" not in bingo_round_columns:
            connection.execute(
                "ALTER TABLE bingo_rounds ADD COLUMN winner_started_at TEXT"
            )

        # --------------------------------------------------------
        # Bingo game tables
        # --------------------------------------------------------
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS bingo_rooms (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                bet_amount REAL NOT NULL UNIQUE,
                max_cards INTEGER NOT NULL DEFAULT 100,
                min_players INTEGER NOT NULL DEFAULT 2,
                max_players INTEGER NOT NULL DEFAULT 100,
                countdown_seconds INTEGER NOT NULL DEFAULT 60,
                commission_percent REAL NOT NULL DEFAULT 10,
                is_active INTEGER NOT NULL DEFAULT 1,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS bingo_cards (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                card_number INTEGER NOT NULL UNIQUE,
                card_data TEXT NOT NULL,
                is_active INTEGER NOT NULL DEFAULT 1,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS bingo_rounds (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                room_id INTEGER NOT NULL,
                round_number INTEGER NOT NULL,
                bet_amount REAL NOT NULL DEFAULT 0,
                status TEXT NOT NULL DEFAULT 'WAITING',
                started_at TEXT,
                countdown_started_at TEXT,
                playing_started_at TEXT,
                winner_started_at TEXT,
                finished_at TEXT,
                next_call_at TEXT,
                total_pot REAL NOT NULL DEFAULT 0,
                commission_percent REAL NOT NULL DEFAULT 10,
                commission_amount REAL NOT NULL DEFAULT 0,
                prize_pool REAL NOT NULL DEFAULT 0,
                called_count INTEGER NOT NULL DEFAULT 0,
                winner_count INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (room_id) REFERENCES bingo_rooms(id),
                UNIQUE(room_id, round_number)
            );

            CREATE TABLE IF NOT EXISTS bingo_players (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                round_id INTEGER NOT NULL,
                user_id INTEGER NOT NULL,
                card_id INTEGER NOT NULL,
                bet_amount REAL NOT NULL,
                status TEXT NOT NULL DEFAULT 'ACTIVE',
                joined_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                left_at TEXT,
                FOREIGN KEY (round_id) REFERENCES bingo_rounds(id),
                FOREIGN KEY (user_id) REFERENCES users(id),
                FOREIGN KEY (card_id) REFERENCES bingo_cards(id),
                UNIQUE(round_id, card_id),
                UNIQUE(round_id, user_id, card_id)
            );

            CREATE TABLE IF NOT EXISTS bingo_calls (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                round_id INTEGER NOT NULL,
                call_order INTEGER NOT NULL,
                number INTEGER NOT NULL,
                called_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (round_id) REFERENCES bingo_rounds(id),
                UNIQUE(round_id, call_order),
                UNIQUE(round_id, number)
            );

            CREATE TABLE IF NOT EXISTS bingo_winners (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                round_id INTEGER NOT NULL,
                player_id INTEGER NOT NULL,
                user_id INTEGER NOT NULL,
                card_id INTEGER NOT NULL,
                pattern TEXT NOT NULL,
                prize_amount REAL NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (round_id) REFERENCES bingo_rounds(id),
                FOREIGN KEY (player_id) REFERENCES bingo_players(id),
                FOREIGN KEY (user_id) REFERENCES users(id),
                FOREIGN KEY (card_id) REFERENCES bingo_cards(id),
                UNIQUE(round_id, player_id, pattern)
            );

            CREATE TABLE IF NOT EXISTS admin_users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                telegram_user_id INTEGER NOT NULL UNIQUE,
                created_by INTEGER,
                is_active INTEGER NOT NULL DEFAULT 1,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS admin_grants (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                admin_id INTEGER NOT NULL,
                grant_key TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (admin_id) REFERENCES admin_users(id) ON DELETE CASCADE,
                UNIQUE(admin_id, grant_key)
            );

            CREATE TABLE IF NOT EXISTS admin_activity_log (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                admin_telegram_id INTEGER NOT NULL,
                action TEXT NOT NULL,
                details TEXT,
                target_telegram_id INTEGER,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS bingo_patterns (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                pattern_key TEXT NOT NULL UNIQUE,
                pattern_name TEXT NOT NULL,
                is_enabled INTEGER NOT NULL DEFAULT 1,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            );
            """
        )

        # Default Bingo commission setting. Existing admin-edited value is preserved.
        connection.execute(
            """
            INSERT OR IGNORE INTO system_settings (setting_key, setting_value)
            VALUES ('bingo_commission_percent', '10')
            """
        )

        # Default Bingo rooms. Existing rooms are preserved.
        for bet in (10, 20, 50, 100):
            connection.execute(
                """
                INSERT OR IGNORE INTO bingo_rooms
                (bet_amount, max_cards, min_players, max_players,
                 countdown_seconds, commission_percent)
                VALUES (?, 100, 2, 100, 60, 10)
                """,
                (float(bet),),
            )

        # Standard 75-ball Bingo winning patterns.
        patterns = [
            ("HORIZONTAL", "Horizontal Line"),
            ("VERTICAL", "Vertical Line"),
            ("DIAGONAL", "Diagonal"),
            ("FOUR_CORNERS", "Four Corners"),
            ("X", "X Pattern"),
            ("PLUS", "Plus Pattern"),
            ("FULL_HOUSE", "Full House / Blackout"),
        ]
        for key, name in patterns:
            connection.execute(
                """
                INSERT OR IGNORE INTO bingo_patterns
                (pattern_key, pattern_name, is_enabled)
                VALUES (?, ?, 1)
                """,
                (key, name),
            )

        # Generate the card pool once. Existing cards are never replaced.
        # Each card uses standard 75-ball Bingo columns B-I-N-G-O.
        existing_cards = connection.execute(
            "SELECT COUNT(*) AS total FROM bingo_cards"
        ).fetchone()["total"]
        if int(existing_cards) == 0:
            import json
            import random

            for card_number in range(1, 101):
                columns = [
                    random.sample(range(1, 16), 5),
                    random.sample(range(16, 31), 5),
                    random.sample(range(31, 46), 5),
                    random.sample(range(46, 61), 5),
                    random.sample(range(61, 76), 5),
                ]
                grid = []
                for row in range(5):
                    values = [columns[col][row] for col in range(5)]
                    if row == 2:
                        values[2] = 0  # FREE center square
                    grid.append(values)

                connection.execute(
                    """
                    INSERT INTO bingo_cards (card_number, card_data)
                    VALUES (?, ?)
                    """,
                    (card_number, json.dumps(grid, separators=(",", ":"))),
                )

        connection.commit()

    finally:
        connection.close()


