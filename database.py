def ensure_bingo_card_pool(required_count):
    """Expand the demo Bingo card pool without replacing existing cards."""
    import json
    import random

    required_count = max(1, int(required_count))
    connection = get_connection()
    try:
        current = connection.execute(
            "SELECT COALESCE(MAX(card_number), 0) AS max_number FROM bingo_cards"
        ).fetchone()["max_number"]
        current = int(current or 0)
        if current >= required_count:
            return current

        for card_number in range(current + 1, required_count + 1):
            columns = [
                random.sample(range(1, 16), 5),
                random.sample(range(16, 31), 5),
                random.sample(range(31, 46), 5),
                random.sample(range(46, 61), 5),
                random.sample(range(61, 76), 5),
            ]
            grid = []
            for row in range(5):
                values = [columns[col][row] for col in range(5)]
                if row == 2:
                    values[2] = 0
                grid.append(values)
            connection.execute(
                "INSERT INTO bingo_cards (card_number, card_data) VALUES (?, ?)",
                (card_number, json.dumps(grid, separators=(",", ":"))),
            )
        connection.commit()
        return required_count
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def create_bingo_room(bet_amount, max_cards=100):
    try:
        bet_amount = float(bet_amount)
        max_cards = int(max_cards)
        if bet_amount <= 0 or max_cards < 2:
            return None, "invalid_values"
    except (TypeError, ValueError):
        return None, "invalid_values"

    connection = get_connection()
    try:
        existing = connection.execute(
            "SELECT * FROM bingo_rooms WHERE bet_amount = ?",
            (bet_amount,),
        ).fetchone()
        if existing:
            return existing, "already_exists"
        commission = get_system_setting_float("bingo_commission_percent", 10)
        connection.execute(
            """INSERT INTO bingo_rooms
               (bet_amount, max_cards, min_players, max_players,
                countdown_seconds, commission_percent, is_active)
               VALUES (?, ?, 2, ?, 60, ?, 1)""",
            (bet_amount, max_cards, max_cards, commission),
        )
        connection.commit()
        room = connection.execute(
            "SELECT * FROM bingo_rooms WHERE bet_amount = ?", (bet_amount,)
        ).fetchone()
    finally:
        connection.close()

    ensure_bingo_card_pool(max_cards)
    return room, "created"


def update_bingo_room(room_id, bet_amount=None, max_cards=None, is_active=None):
    connection = get_connection()
    try:
        room = connection.execute(
            "SELECT * FROM bingo_rooms WHERE id = ?", (int(room_id),)
        ).fetchone()
        if not room:
            return None, "not_found"

        new_bet = float(room["bet_amount"] if bet_amount is None else bet_amount)
        new_max = int(room["max_cards"] if max_cards is None else max_cards)
        new_active = int(room["is_active"] if is_active is None else (1 if is_active else 0))
        if new_bet <= 0 or new_max < 2:
            return room, "invalid_values"

        duplicate = connection.execute(
            "SELECT id FROM bingo_rooms WHERE bet_amount = ? AND id <> ?",
            (new_bet, int(room_id)),
        ).fetchone()
        if duplicate:
            return room, "bet_exists"

        connection.execute(
            """UPDATE bingo_rooms
               SET bet_amount = ?, max_cards = ?, max_players = ?,
                   is_active = ?, updated_at = CURRENT_TIMESTAMP
               WHERE id = ?""",
            (new_bet, new_max, new_max, new_active, int(room_id)),
        )
        connection.commit()
        updated = connection.execute(
            "SELECT * FROM bingo_rooms WHERE id = ?", (int(room_id),)
        ).fetchone()
    finally:
        connection.close()

    ensure_bingo_card_pool(new_max)
    return updated, "updated"


def delete_bingo_room(room_id):
    """Soft-disable a room; existing game history remains intact."""
    return update_bingo_room(room_id, is_active=False)


