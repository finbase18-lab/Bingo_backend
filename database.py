def call_next_bingo_number(round_id):
    """Draw one unused number from 1-75 and record it atomically."""
    import random

    connection = get_connection()
    try:
        connection.execute("BEGIN IMMEDIATE")

        round_row = connection.execute(
            "SELECT * FROM bingo_rounds WHERE id = ?", (round_id,)
        ).fetchone()

        if not round_row:
            connection.rollback()
            return None, "round_not_found"

        if round_row["status"] != "PLAYING":
            connection.rollback()
            return None, "round_not_playing"

        used = {
            int(row["number"])
            for row in connection.execute(
                "SELECT number FROM bingo_calls WHERE round_id = ?",
                (round_id,),
            ).fetchall()
        }

        remaining = [n for n in range(1, BINGO_TOTAL_NUMBERS + 1) if n not in used]
        if not remaining:
            connection.rollback()
            return None, "no_numbers_remaining"

        number = random.choice(remaining)
        order = len(used) + 1

        cur = connection.execute(
            """INSERT INTO bingo_calls (round_id, call_order, number)
               VALUES (?, ?, ?)""",
            (round_id, order, number),
        )

        connection.execute(
            """UPDATE bingo_rounds
               SET called_count = ?, next_call_at = NULL
               WHERE id = ?""",
            (order, round_id),
        )

        connection.commit()

        call = connection.execute(
            "SELECT * FROM bingo_calls WHERE id = ?", (cur.lastrowid,)
        ).fetchone()
        return call, "called"
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def find_bingo_winners(round_id):
    """Find active cards that currently satisfy an enabled pattern.

    One winning record is selected per card using the enabled pattern order.
    This prevents a single card matching X + diagonal, for example, from
    receiving multiple shares of the prize pool.
    """
    connection = get_connection()
    try:
        round_row = connection.execute(
            "SELECT * FROM bingo_rounds WHERE id = ?", (round_id,)
        ).fetchone()
        if not round_row:
            return None, "round_not_found"

        called = [
            int(row["number"])
            for row in connection.execute(
                """SELECT number FROM bingo_calls
                   WHERE round_id = ? ORDER BY call_order ASC""",
                (round_id,),
            ).fetchall()
        ]

        patterns = connection.execute(
            """SELECT pattern_key, pattern_name
               FROM bingo_patterns
               WHERE is_enabled = 1 ORDER BY id ASC"""
        ).fetchall()

        players = connection.execute(
            """SELECT p.*, c.card_data, c.card_number,
                      u.telegram_user_id, u.username, u.first_name
               FROM bingo_players p
               JOIN bingo_cards c ON c.id = p.card_id
               JOIN users u ON u.id = p.user_id
               WHERE p.round_id = ? AND p.status = 'ACTIVE'
               ORDER BY p.id ASC""",
            (round_id,),
        ).fetchall()

        winners = []
        for player in players:
            matched_pattern = None
            for pattern in patterns:
                if bingo_card_matches_pattern(
                    player["card_data"],
                    called,
                    pattern["pattern_key"],
                ):
                    matched_pattern = pattern
                    break

            if matched_pattern:
                winners.append({
                    "player_id": int(player["id"]),
                    "user_id": int(player["user_id"]),
                    "telegram_user_id": int(player["telegram_user_id"]),
                    "card_id": int(player["card_id"]),
                    "card_number": int(player["card_number"]),
                    "pattern": matched_pattern["pattern_key"],
                    "pattern_name": matched_pattern["pattern_name"],
                })

        return winners, "ok"
    finally:
        connection.close()


def finish_bingo_round_with_winners(round_id):
    """Finalize a round, split the prize among winning cards and credit winners.

    The operation is idempotent: once the round reaches WINNER/RESULT/FINISHED,
    it will not credit the same winning card again.
    """
    connection = get_connection()
    try:
        connection.execute("BEGIN IMMEDIATE")

        round_row = connection.execute(
            """SELECT r.*
               FROM bingo_rounds r
               JOIN bingo_rooms rm ON rm.id = r.room_id
               WHERE r.id = ?""",
            (round_id,),
        ).fetchone()

        if not round_row:
            connection.rollback()
            return None, "round_not_found"

        if round_row["status"] not in ("PLAYING", "WINNER"):
            connection.rollback()
            return None, "round_not_playing"

        called = [
            int(row["number"])
            for row in connection.execute(
                """SELECT number FROM bingo_calls
                   WHERE round_id = ? ORDER BY call_order ASC""",
                (round_id,),
            ).fetchall()
        ]

        patterns = connection.execute(
            """SELECT pattern_key, pattern_name
               FROM bingo_patterns
               WHERE is_enabled = 1 ORDER BY id ASC"""
        ).fetchall()

        players = connection.execute(
            """SELECT p.*, c.card_data, c.card_number,
                      u.telegram_user_id
               FROM bingo_players p
               JOIN bingo_cards c ON c.id = p.card_id
               JOIN users u ON u.id = p.user_id
               WHERE p.round_id = ? AND p.status IN ('ACTIVE', 'WINNER')
               ORDER BY p.id ASC""",
            (round_id,),
        ).fetchall()

        winner_candidates = []
        existing_winners = {
            int(row["player_id"])
            for row in connection.execute(
                "SELECT player_id FROM bingo_winners WHERE round_id = ?",
                (round_id,),
            ).fetchall()
        }

        for player in players:
            if int(player["id"]) in existing_winners:
                continue

            matched = None
            for pattern in patterns:
                if bingo_card_matches_pattern(
                    player["card_data"],
                    called,
                    pattern["pattern_key"],
                ):
                    matched = pattern
                    break

            if matched:
                winner_candidates.append((player, matched))

        if not winner_candidates:
            connection.rollback()
            return None, "no_winner"

        total_pot = round(sum(
            float(row["bet_amount"])
            for row in players
        ), 2)
        commission_percent = max(
            0.0,
            min(100.0, float(round_row["commission_percent"] or 0)),
        )
        commission_amount = round(total_pot * commission_percent / 100.0, 2)
        prize_pool = round(total_pot - commission_amount, 2)
        winner_count = len(winner_candidates)
        share = round(prize_pool / winner_count, 2) if winner_count else 0.0

        # Correct any one-cent rounding difference on the final winner so the
        # distributed amount never exceeds the calculated prize pool.
        distributed = 0.0

        for index, (player, pattern) in enumerate(winner_candidates):
            if index == winner_count - 1:
                prize = round(prize_pool - distributed, 2)
            else:
                prize = share
            distributed = round(distributed + prize, 2)

            connection.execute(
                """INSERT INTO bingo_winners
                   (round_id, player_id, user_id, card_id, pattern, prize_amount)
                   VALUES (?, ?, ?, ?, ?, ?)""",
                (
                    round_id,
                    player["id"],
                    player["user_id"],
                    player["card_id"],
                    pattern["pattern_key"],
                    prize,
                ),
            )

            before = float(connection.execute(
                "SELECT withdrawable_balance FROM users WHERE id = ?",
                (player["user_id"],),
            ).fetchone()["withdrawable_balance"])
            after = round(before + prize, 2)

            connection.execute(
                """UPDATE users
                   SET withdrawable_balance = ?,
                       total_won = total_won + ?,
                       updated_at = CURRENT_TIMESTAMP
                   WHERE id = ?""",
                (after, prize, player["user_id"]),
            )

            connection.execute(
                """INSERT INTO wallet_transactions
                   (user_id, transaction_type, balance_type, amount,
                    balance_before, balance_after, description)
                   VALUES (?, ?, ?, ?, ?, ?, ?)""",
                (
                    player["user_id"],
                    "BINGO_WIN",
                    "withdrawable_balance",
                    prize,
                    before,
                    after,
                    f"Bingo round #{round_row['round_number']} prize - {pattern['pattern_name']}",
                ),
            )

            connection.execute(
                "UPDATE bingo_players SET status = 'WINNER' WHERE id = ?",
                (player["id"],),
            )

        connection.execute(
            """UPDATE bingo_players
               SET status = 'LOST'
               WHERE round_id = ? AND status = 'ACTIVE'""",
            (round_id,),
        )

        connection.execute(
            """UPDATE bingo_rounds
               SET status = 'WINNER',
                   winner_started_at = ?,
                   total_pot = ?,
                   commission_amount = ?,
                   prize_pool = ?,
                   winner_count = ?
               WHERE id = ?""",
            (
                _now_text(),
                total_pot,
                commission_amount,
                prize_pool,
                winner_count,
                round_id,
            ),
        )

        connection.commit()

        return {
            "round_id": int(round_id),
            "round_number": int(round_row["round_number"]),
            "total_pot": total_pot,
            "commission_percent": commission_percent,
            "commission_amount": commission_amount,
            "prize_pool": prize_pool,
            "winner_count": winner_count,
            "distributed_prize": distributed,
        }, "finished"
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def _now_text():
    """Return an ISO-8601 UTC timestamp safe for both SQLite and PostgreSQL text columns."""
    return datetime.now(timezone.utc).isoformat()


def set_bingo_winner_started_at(round_id):
    """Repair/initialize the winner-display timestamp for a WINNER round."""
    connection = get_connection()
    try:
        cur = connection.execute(
            """UPDATE bingo_rounds
               SET winner_started_at = COALESCE(winner_started_at, ?)
               WHERE id = ? AND status = 'WINNER'""",
            (_now_text(), round_id),
        )
        connection.commit()
        return cur.rowcount > 0
    finally:
        connection.close()


def set_bingo_round_result(round_id):
    """Move a completed WINNER round to RESULT, ready for the next round."""
    connection = get_connection()
    try:
        cur = connection.execute(
            """UPDATE bingo_rounds
               SET status = 'RESULT',
                   finished_at = COALESCE(finished_at, ?)
               WHERE id = ? AND status = 'WINNER'""",
            (_now_text(), round_id),
        )
        connection.commit()
        return cur.rowcount > 0
    finally:
        connection.close()


def finish_bingo_round(round_id):
    """Mark a RESULT round as FINISHED."""
    connection = get_connection()
    try:
        cur = connection.execute(
            """UPDATE bingo_rounds
               SET status = 'FINISHED',
                   finished_at = COALESCE(finished_at, ?)
               WHERE id = ? AND status = 'RESULT'""",
            (_now_text(), round_id),
        )
        connection.commit()
        return cur.rowcount > 0
    finally:
        connection.close()


def get_bingo_dashboard_data():
    """Return active rooms with their current round and player/card counts."""
    connection = get_connection()
    try:
        return connection.execute(
            """SELECT
                   rm.id AS room_id,
                   rm.bet_amount,
                   rm.max_cards,
                   rm.min_players,
                   rm.max_players,
                   rm.countdown_seconds,
                   COALESCE(r.commission_percent, rm.commission_percent) AS commission_percent,
                   rm.is_active,
                   r.id AS round_id,
                   r.round_number,
                   r.status,
                   r.started_at,
                   r.countdown_started_at,
                   r.playing_started_at,
                   r.finished_at,
                   r.total_pot,
                   r.commission_amount,
                   r.prize_pool,
                   r.called_count,
                   r.winner_count,
                   COALESCE((
                       SELECT COUNT(*) FROM bingo_players p
                       WHERE p.round_id = r.id AND p.status = 'ACTIVE'
                   ), 0) AS active_players,
                   COALESCE((
                       SELECT COUNT(*) FROM bingo_players p
                       WHERE p.round_id = r.id
                   ), 0) AS selected_cards
               FROM bingo_rooms rm
               LEFT JOIN bingo_rounds r
                 ON r.id = (
                     SELECT r2.id
                     FROM bingo_rounds r2
                     WHERE r2.room_id = rm.id
                       AND r2.status IN ('WAITING', 'COUNTDOWN', 'PLAYING', 'WINNER', 'RESULT')
                     ORDER BY r2.id DESC
                     LIMIT 1
                 )
               WHERE rm.is_active = 1
               ORDER BY rm.bet_amount ASC"""
        ).fetchall()
    finally:
        connection.close()


