USE_POSTGRES = bool(DATABASE_URL)


class _PGCursor:
    """Small compatibility wrapper so the existing SQLite-style code can run on PostgreSQL."""
    def __init__(self, cursor):
        self._cursor = cursor
        self._lastrowid = None

    @property
    def lastrowid(self):
        return self._lastrowid

    def _set_lastrowid(self):
        if self._lastrowid is not None:
            return
        try:
            row = self._cursor.fetchone()
            if row and "id" in row:
                self._lastrowid = row["id"]
        except Exception:
            pass

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class _PGConnection:
    def __init__(self, url):
        if psycopg is None:
            raise RuntimeError(
                "PostgreSQL support requires psycopg. Add 'psycopg[binary]' to requirements.txt."
            )
        self._connection = psycopg.connect(
            url,
            row_factory=dict_row,
            connect_timeout=15,
        )

    @staticmethod
    def _transform_sql(sql, add_returning=False, insert_or_ignore=False):
        if not isinstance(sql, str):
            return sql

        sql = sql.replace("BEGIN IMMEDIATE", "BEGIN")
        sql = sql.replace("BEGIN EXCLUSIVE", "BEGIN")
        sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")

        # Telegram user IDs can be larger than PostgreSQL's 32-bit INTEGER.
        # Keep SQLite INTEGER locally, but use BIGINT on PostgreSQL.
        sql = re.sub(
            r"\btelegram_user_id\s+INTEGER\b",
            "telegram_user_id BIGINT",
            sql,
            flags=re.IGNORECASE,
        )

        # Convert SQLite placeholders.
        sql = sql.replace("?", "%s")

        # Convert SQLite's INSERT OR IGNORE to PostgreSQL.
        if re.search(r"INSERT\s+OR\s+IGNORE\s+INTO", sql, flags=re.IGNORECASE):
            sql = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, flags=re.IGNORECASE)
            insert_or_ignore = True

        # Convert SQLite elapsed-time expressions to PostgreSQL. Bingo
        # timestamps are stored as TEXT, so cast them to timestamptz.
        sql = re.sub(
            r"\(julianday\('now'\)\s*-\s*julianday\(([^)]+)\)\)\s*\*\s*86400\.0",
            r"EXTRACT(EPOCH FROM (CURRENT_TIMESTAMP - \1::timestamptz))",
            sql,
            flags=re.IGNORECASE,
        )

        # PostgreSQL requires ON CONFLICT to appear BEFORE RETURNING.
        if insert_or_ignore:
            stripped = sql.rstrip().rstrip(";")
            if not re.search(r"\bON\s+CONFLICT\b", stripped, flags=re.IGNORECASE):
                stripped += " ON CONFLICT DO NOTHING"
            sql = stripped

        if add_returning:
            stripped = sql.rstrip().rstrip(";")
            if not re.search(r"\bRETURNING\b", stripped, flags=re.IGNORECASE):
                stripped += " RETURNING id"
            sql = stripped

        return sql.rstrip().rstrip(";") + ";"

    def execute(self, sql, params=None):
        if isinstance(sql, str):
            # Translate SQLite PRAGMA table_info(...) into PostgreSQL metadata.
            m = re.fullmatch(r"\s*PRAGMA\s+table_info\(([^)]+)\)\s*;?\s*", sql, flags=re.IGNORECASE)
            if m:
                table = m.group(1).strip().strip('"').strip("'")
                # Return the subset of SQLite PRAGMA table_info() fields that
                # this application actually uses. Avoid pg_index/regclass here
                # because this compatibility query runs during first-time
                # PostgreSQL schema initialization.
                cur = self._connection.execute(
                    """SELECT ordinal_position AS cid,
                              column_name AS name,
                              data_type AS type,
                              CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull,
                              NULL AS dflt_value,
                              0 AS pk
                       FROM information_schema.columns
                       WHERE table_schema = current_schema()
                         AND table_name = %s
                       ORDER BY ordinal_position""",
                    (table,),
                )
                return _PGCursor(cur)

            original = sql
            # Detect INSERT statements whose caller expects cursor.lastrowid.
            is_insert = bool(re.match(r"\s*INSERT\s+", original, flags=re.IGNORECASE))
            table_match = re.match(r'\s*INSERT(?:\s+OR\s+IGNORE)?\s+INTO\s+([\w"]+)', original, flags=re.IGNORECASE)
            table_name = table_match.group(1).strip('"').lower() if table_match else ""
            needs_returning = is_insert and table_name not in {"system_settings"}
            sql = self._transform_sql(
                original,
                add_returning=needs_returning,
                insert_or_ignore=bool(re.search(r"INSERT\s+OR\s+IGNORE", original, flags=re.IGNORECASE)),
            )

        cur = self._connection.execute(sql, params)
        wrapped = _PGCursor(cur)
        if isinstance(sql, str) and re.search(r"\bINSERT\s+INTO\b", sql, flags=re.IGNORECASE) and re.search(r"\bRETURNING\s+id\b", sql, flags=re.IGNORECASE):
            try:
                row = cur.fetchone()
                if row and "id" in row:
                    wrapped._lastrowid = row["id"]
            except Exception:
                pass
        return wrapped

    def executescript(self, script):
        # The schema contains independent CREATE/INSERT statements. Execute each
        # statement separately so PostgreSQL can process the SQLite-derived script.
        statements = [s.strip() for s in script.split(";") if s.strip()]
        for statement in statements:
            self.execute(statement)

    def commit(self):
        return self._connection.commit()

    def rollback(self):
        return self._connection.rollback()

    def close(self):
        return self._connection.close()


