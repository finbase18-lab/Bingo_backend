def create_deposit_request(
    telegram_user_id,
    bank_id,
    amount,
    transaction_id,
):
    amount = float(amount)
    transaction_id = str(transaction_id or "").strip()

    if amount <= 0:
        return None, "invalid_amount"

    if len(transaction_id) < 3:
        return None, "invalid_transaction_id"

    connection = get_connection()

    try:
        user = connection.execute(
            "SELECT * FROM users WHERE telegram_user_id = ?",
            (telegram_user_id,),
        ).fetchone()

        if not user:
            return None, "user_not_found"

        bank = connection.execute(
            """
            SELECT *
            FROM demo_banks
            WHERE id = ? AND is_active = 1
            """,
            (bank_id,),
        ).fetchone()

        if not bank:
            return None, "bank_not_found"

        # A player may have pending deposits at different banks, but only
        # one pending request for the same bank at a time.
        pending = connection.execute(
            """
            SELECT id
            FROM deposit_requests
            WHERE user_id = ?
              AND bank_id = ?
              AND status = 'PENDING'
            """,
            (user["id"], bank_id),
        ).fetchone()

        if pending:
            return None, "pending_same_bank"

        cursor = connection.execute(
            """
            INSERT INTO deposit_requests (
                user_id,
                bank_id,
                amount,
                transaction_id,
                status
            )
            VALUES (?, ?, ?, ?, 'PENDING')
            """,
            (
                user["id"],
                bank_id,
                amount,
                transaction_id,
            ),
        )

        request_id = cursor.lastrowid
        connection.commit()
        return request_id, "created"

    finally:
        connection.close()



