# ============================================================


def create_withdrawal_request(
    telegram_user_id,
    bank_id,
    amount,
    account_number,
    account_name,
):
    amount = float(amount)

    if amount <= 0:
        return None, "invalid_amount"

    connection = get_connection()

    try:
        user = connection.execute(
            "SELECT * FROM users WHERE telegram_user_id = ?",
            (telegram_user_id,),
        ).fetchone()

        if not user:
            return None, "user_not_found"

        bank = connection.execute(
            """
            SELECT *
            FROM demo_banks
            WHERE id = ? AND is_active = 1
            """,
            (bank_id,),
        ).fetchone()

        if not bank:
            return None, "bank_not_found"

        def setting_float(key, default):
            row = connection.execute(
                "SELECT setting_value FROM system_settings WHERE setting_key = ?",
                (key,),
            ).fetchone()
            if not row:
                return float(default)
            try:
                return float(row["setting_value"])
            except (TypeError, ValueError):
                return float(default)

        first_deposit_required = setting_float("first_deposit_required", 200)
        min_withdrawal = setting_float("min_withdrawal", 100)
        max_withdrawal = setting_float("max_withdrawal", 10000)

        # Requirement applies only until the player's first approved withdrawal.
        if (
            float(user["total_withdrawn"] or 0) <= 0
            and float(user["total_deposited"] or 0) < first_deposit_required
        ):
            return None, "first_deposit_required"

        if amount < min_withdrawal:
            return None, "below_minimum"

        if max_withdrawal > 0 and amount > max_withdrawal:
            return None, "above_maximum"

        withdrawable = float(user["withdrawable_balance"])
        if withdrawable < amount:
            return None, "insufficient_balance"

        pending = connection.execute(
            """
            SELECT id
            FROM withdrawal_requests
            WHERE user_id = ? AND status = 'PENDING'
            """,
            (user["id"],),
        ).fetchone()

        if pending:
            return None, "pending_exists"

        before = withdrawable
        after = before - amount

        connection.execute(
            """
            UPDATE users
            SET withdrawable_balance = ?, updated_at = CURRENT_TIMESTAMP
            WHERE id = ?
            """,
            (after, user["id"]),
        )

        cursor = connection.execute(
            """
            INSERT INTO withdrawal_requests (
                user_id,
                bank_id,
                amount,
                account_number,
                account_name,
                status
            )
            VALUES (?, ?, ?, ?, ?, 'PENDING')
            """,
            (
                user["id"],
                bank_id,
                amount,
                account_number,
                account_name,
            ),
        )

        request_id = cursor.lastrowid

        connection.execute(
            """
            INSERT INTO wallet_transactions (
                user_id,
                transaction_type,
                balance_type,
                amount,
                balance_before,
                balance_after,
                description
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                user["id"],
                "WITHDRAWAL_PENDING",
                "withdrawable_balance",
                -amount,
                before,
                after,
                "Demo withdrawal pending - amount reserved",
            ),
        )

        connection.commit()
        return request_id, "created"

    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()



