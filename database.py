def calculate_bingo_round_financials(round_id):
    """Calculate the pot, commission and prize pool without changing the round."""
    connection = get_connection()
    try:
        row = connection.execute(
            """SELECT
                   r.id,
                   r.room_id,
                   r.commission_percent,
                   COALESCE(SUM(p.bet_amount), 0) AS total_pot
               FROM bingo_rounds r
               JOIN bingo_rooms rm ON rm.id = r.room_id
               LEFT JOIN bingo_players p
                 ON p.round_id = r.id
                AND p.status IN ('ACTIVE', 'WINNER', 'LOST')
               WHERE r.id = ?
               GROUP BY r.id, r.room_id, rm.commission_percent""",
            (round_id,),
        ).fetchone()

        if not row:
            return None

        total_pot = round(float(row["total_pot"]), 2)
        commission_percent = float(row["commission_percent"] or 0)
        commission_percent = max(0.0, min(100.0, commission_percent))
        commission_amount = round(total_pot * commission_percent / 100.0, 2)
        prize_pool = round(total_pot - commission_amount, 2)

        return {
            "round_id": int(row["id"]),
            "total_pot": total_pot,
            "commission_percent": commission_percent,
            "commission_amount": commission_amount,
            "prize_pool": prize_pool,
        }
    finally:
        connection.close()


def start_bingo_countdown(round_id):
    """Move a waiting round into its one-minute countdown."""
    connection = get_connection()
    try:
        connection.execute("BEGIN IMMEDIATE")

        round_row = connection.execute(
            """SELECT r.*, rm.min_players
               FROM bingo_rounds r
               JOIN bingo_rooms rm ON rm.id = r.room_id
               WHERE r.id = ?""",
            (round_id,),
        ).fetchone()

        if not round_row:
            connection.rollback()
            return None, "round_not_found"

        if round_row["status"] != "WAITING":
            connection.rollback()
            return round_row, "not_waiting"

        player_count = int(connection.execute(
            """SELECT COUNT(*) AS total
               FROM bingo_players
               WHERE round_id = ? AND status = 'ACTIVE'""",
            (round_id,),
        ).fetchone()["total"])

        if player_count < int(round_row["min_players"]):
            connection.rollback()
            return round_row, "not_enough_players"

        connection.execute(
            """UPDATE bingo_rounds
               SET status = 'COUNTDOWN',
                   countdown_started_at = CURRENT_TIMESTAMP,
                   started_at = CURRENT_TIMESTAMP
               WHERE id = ? AND status = 'WAITING'""",
            (round_id,),
        )
        connection.commit()

        return connection.execute(
            "SELECT * FROM bingo_rounds WHERE id = ?", (round_id,)
        ).fetchone(), "countdown_started"
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def start_bingo_playing(round_id):
    """Start a countdown round after the required countdown has elapsed."""
    connection = get_connection()
    try:
        connection.execute("BEGIN IMMEDIATE")

        row = connection.execute(
            """SELECT r.*, rm.min_players, rm.countdown_seconds
               FROM bingo_rounds r
               JOIN bingo_rooms rm ON rm.id = r.room_id
               WHERE r.id = ?""",
            (round_id,),
        ).fetchone()

        if not row:
            connection.rollback()
            return None, "round_not_found"

        if row["status"] != "COUNTDOWN":
            connection.rollback()
            return row, "not_countdown"

        player_count = int(connection.execute(
            """SELECT COUNT(*) AS total FROM bingo_players
               WHERE round_id = ? AND status = 'ACTIVE'""",
            (round_id,),
        ).fetchone()["total"])

        if player_count < int(row["min_players"]):
            connection.rollback()
            return row, "not_enough_players"

        # Keep the source expression SQLite-compatible; the PostgreSQL
        # compatibility layer converts it to a timezone-aware epoch value.
        elapsed = connection.execute(
            """SELECT
                   (julianday('now') - julianday(countdown_started_at)) * 86400.0
               AS seconds_elapsed
               FROM bingo_rounds
               WHERE id = ?""",
            (round_id,),
        ).fetchone()["seconds_elapsed"]

        required = int(row["countdown_seconds"] or BINGO_DEFAULT_COUNTDOWN_SECONDS)
        if elapsed is None or float(elapsed) < required:
            connection.rollback()
            return row, "countdown_not_finished"

        totals = connection.execute(
            """SELECT COALESCE(SUM(bet_amount), 0) AS total_pot
               FROM bingo_players
               WHERE round_id = ? AND status = 'ACTIVE'""",
            (round_id,),
        ).fetchone()

        total_pot = round(float(totals["total_pot"] or 0), 2)
        commission_percent = max(0.0, min(100.0, float(row["commission_percent"] or 0)))
        commission_amount = round(total_pot * commission_percent / 100.0, 2)
        prize_pool = round(total_pot - commission_amount, 2)

        connection.execute(
            """UPDATE bingo_rounds
               SET status = 'PLAYING',
                   playing_started_at = CURRENT_TIMESTAMP,
                   total_pot = ?,
                   commission_amount = ?,
                   prize_pool = ?
               WHERE id = ? AND status = 'COUNTDOWN'""",
            (total_pot, commission_amount, prize_pool, round_id),
        )
        connection.commit()

        return connection.execute(
            "SELECT * FROM bingo_rounds WHERE id = ?", (round_id,)
        ).fetchone(), "playing"
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


