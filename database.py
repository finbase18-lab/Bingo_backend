def get_bingo_winners(round_id):
    """Return persisted winner records for a round.

    This is intentionally different from find_bingo_winners(), which performs
    a live pattern check and returns a (winners, status) tuple. The Mini App
    needs the records that were actually paid and stored in bingo_winners.
    """
    connection = get_connection()
    try:
        rows = connection.execute(
            """SELECT
                   w.*,
                   c.card_number,
                   c.card_data,
                   u.telegram_user_id,
                   u.username,
                   u.first_name,
                   u.last_name,
                   COALESCE(bp.pattern_name, w.pattern) AS pattern_name
               FROM bingo_winners w
               JOIN bingo_cards c ON c.id = w.card_id
               JOIN users u ON u.id = w.user_id
               LEFT JOIN bingo_patterns bp ON bp.pattern_key = w.pattern
               WHERE w.round_id = ?
               ORDER BY w.id ASC""",
            (round_id,),
        ).fetchall()
        return [dict(row) for row in rows]
    finally:
        connection.close()

